/* eslint-disable @typescript-eslint/no-explicit-any */
import { inngest } from "./client";
import { sql } from "../db";
import { uploadToCloudinary, getResponsiveImageUrls } from "../cloudinary";
import { PredictionServiceClient, helpers } from '@google-cloud/aiplatform';

// Initialize Vertex AI client
const PROJECT_ID = process.env.GOOGLE_CLOUD_PROJECT || 'gul-tekin-muhendislik';
const LOCATION = process.env.GOOGLE_CLOUD_LOCATION || 'us-central1';

// Get credentials from environment
let credentials: any = undefined;
if (process.env.GOOGLE_APPLICATION_CREDENTIALS_BASE64) {
  // Decode base64 credentials for Vercel deployment
  const credentialsJson = Buffer.from(
    process.env.GOOGLE_APPLICATION_CREDENTIALS_BASE64,
    'base64'
  ).toString('utf-8');
  credentials = JSON.parse(credentialsJson);
}

// Vertex AI Prediction Service Client
const predictionServiceClient = new PredictionServiceClient({
  apiEndpoint: `${LOCATION}-aiplatform.googleapis.com`,
  credentials: credentials, // Use decoded credentials if available
});

// Imagen model endpoint
const IMAGEN_MODEL = `projects/${PROJECT_ID}/locations/${LOCATION}/publishers/google/models/imagen-3.0-generate-001`;

// Generate image with Google Vertex AI Imagen
export const generateImageWithVertexAI = inngest.createFunction(
  {
    id: "generate-image-vertex-ai",
    name: "Generate Image with Google Vertex AI",
    retries: 2
  },
  {
    event: "image/vertex-ai.generate.requested"
  },
  async ({ event, step }) => {
    const {
      prompt,
      contentId,
      aspectRatio = "1:1",
      numberOfImages = 1,
      language = "auto",
      personGeneration = "allow_adult",
      safetySetting = "block_some",
      addWatermark = false
    } = event.data;

    // Step 1: Validate and enhance prompt
    const enhancedPrompt = await step.run("enhance-prompt", async () => {
      let finalPrompt = prompt;

      // If contentId is provided, fetch content details for context
      if (contentId) {
        const content = await sql`
          SELECT title, topic, keywords, image_prompt
          FROM generated_content
          WHERE id = ${contentId}
          LIMIT 1
        `;

        if (content.length > 0) {
          // Use existing image_prompt if available, otherwise use provided prompt
          finalPrompt = content[0].image_prompt || prompt;

          console.log(`Using prompt for content ${contentId}: ${finalPrompt.substring(0, 100)}...`);
        }
      }

      // Add style modifiers for engineering/technical content
      const styleModifiers = ", professional photography, high resolution, clean composition, modern industrial design, technical accuracy";

      // Ensure prompt doesn't exceed Imagen limits (max 2048 characters)
      if (finalPrompt.length + styleModifiers.length <= 2048) {
        finalPrompt += styleModifiers;
      }

      return finalPrompt;
    });

    // Step 2: Prepare Vertex AI request
    const requestPayload = await step.run("prepare-vertex-request", async () => {
      // Create the request payload for Imagen 3
      const instances = [{
        prompt: enhancedPrompt,
        // Imagen 3 specific parameters
      }];

      const parameters = {
        sampleCount: numberOfImages,
        aspectRatio: aspectRatio,
        safetyFilterLevel: safetySetting,
        personGeneration: personGeneration,
        language: language,
        addWatermark: addWatermark,
        // Additional Imagen 3 parameters
        outputOptions: {
          mimeType: "image/png",
          compressionQuality: 95
        }
      };

      return {
        instances,
        parameters
      };
    });

    // Step 3: Generate image with Vertex AI
    const generatedImages = await step.run("generate-with-vertex-ai", async () => {
      try {
        console.log(`Generating image with Vertex AI Imagen 3...`);
        console.log(`Prompt: ${enhancedPrompt.substring(0, 200)}...`);

        // Create the prediction request
        const request = {
          endpoint: IMAGEN_MODEL,
          instances: requestPayload.instances.map(instance => {
            return helpers.toValue(instance) as any;
          }),
          parameters: helpers.toValue(requestPayload.parameters) as any,
        };

        // Make the prediction request
        const [response] = await predictionServiceClient.predict(request);

        if (!response.predictions || response.predictions.length === 0) {
          throw new Error("No images generated by Vertex AI");
        }

        // Extract generated images from response
        const images = response.predictions.map((prediction: any) => {
          const predictionObj = helpers.fromValue(prediction) as {
            bytesBase64Encoded: string;
            mimeType?: string;
          };
          return {
            bytesBase64Encoded: predictionObj.bytesBase64Encoded,
            mimeType: predictionObj.mimeType || "image/png"
          };
        });

        console.log(`Successfully generated ${images.length} image(s) with Vertex AI`);
        return images;
      } catch (error) {
        console.error("Error generating image with Vertex AI:", error);

        // Check for specific Vertex AI errors
        const errorMessage = error instanceof Error ? error.message : String(error);

        if (errorMessage.includes("safety")) {
          throw new Error("Image generation blocked by safety filters. Please modify your prompt.");
        } else if (errorMessage.includes("quota")) {
          throw new Error("Vertex AI quota exceeded. Please try again later.");
        } else if (errorMessage.includes("authentication")) {
          throw new Error("Vertex AI authentication failed. Please check credentials.");
        }

        throw error;
      }
    });

    // Step 4: Upload to Cloudinary
    const uploadedImages = await step.run("upload-to-cloudinary", async () => {
      const uploaded = [];

      for (let i = 0; i < generatedImages.length; i++) {
        const image = generatedImages[i];

        try {
          // Convert base64 to buffer
          const buffer = Buffer.from(image.bytesBase64Encoded, 'base64');

          // Generate a unique public_id
          const timestamp = Date.now();
          const publicId = `vertex-ai/${timestamp}_${i}`;

          // Upload to Cloudinary using the helper function
          const uploadResult = await uploadToCloudinary(buffer, {
            folder: 'vertex-ai',
            public_id: publicId,
            resource_type: 'image',
            format: 'png',
            quality: 'auto:best',
            tags: ['vertex-ai', 'imagen-3', 'generated', 'ai-generated']
          });

          if (!uploadResult.success || !uploadResult.data) {
            throw new Error(uploadResult.error || 'Upload failed');
          }

          // Generate responsive formats
          const responsiveUrls = getResponsiveImageUrls(
            uploadResult.data.public_id,
            [320, 640, 768, 1024, 1280, 1920],
            {
              quality: 'auto:best',
              fetch_format: 'auto'
            }
          );

          uploaded.push({
            url: uploadResult.data.url,
            publicId: uploadResult.data.public_id,
            format: uploadResult.data.format,
            width: uploadResult.data.width,
            height: uploadResult.data.height,
            responsiveUrls
          });

          console.log(`Uploaded image ${i + 1} to Cloudinary: ${uploadResult.data.public_id}`);
        } catch (error) {
          console.error(`Error uploading image ${i + 1} to Cloudinary:`, error);
          throw error;
        }
      }

      return uploaded;
    });

    // Step 5: Save to database (both tables)
    const savedRecords = await step.run("save-to-database", async () => {
      const records = [];

      for (const image of uploadedImages) {
        try {
          // Save to vertex_images table first
          const vertexResult = await sql`
            INSERT INTO vertex_images (
              prompt,
              enhanced_prompt,
              image_url,
              cloudinary_public_id,
              cloudinary_urls,
              responsive_urls,
              model,
              provider,
              aspect_ratio,
              width,
              height,
              format,
              tags,
              content_id,
              generation_params,
              metadata,
              status
            ) VALUES (
              ${prompt},
              ${enhancedPrompt},
              ${image.url},
              ${image.publicId},
              ${JSON.stringify({
                original: image.url,
                publicId: image.publicId
              })},
              ${JSON.stringify(image.responsiveUrls)},
              'imagen-3.0-generate-001',
              'vertex-ai',
              ${aspectRatio},
              ${image.width},
              ${image.height},
              ${image.format},
              ${['vertex-ai', 'imagen-3', 'generated', 'ai-generated', event.data.metadata?.slug].filter(Boolean)},
              ${contentId || null},
              ${JSON.stringify({
                aspectRatio,
                numberOfImages,
                language,
                personGeneration,
                safetySetting,
                addWatermark
              })},
              ${JSON.stringify({
                generatedAt: new Date().toISOString(),
                inngestEventId: event.id,
                service: event.data.metadata?.service,
                slug: event.data.metadata?.slug,
                serviceIndex: event.data.metadata?.serviceIndex
              })},
              'completed'
            )
            ON CONFLICT (cloudinary_public_id) DO UPDATE
            SET updated_at = CURRENT_TIMESTAMP
            RETURNING id, image_url, cloudinary_public_id
          `;

          // Also save to generated_images table for compatibility
          await sql`
            INSERT INTO generated_images (
              prompt,
              enhanced_prompt,
              image_url,
              cloudinary_public_id,
              model,
              provider,
              width,
              height,
              content_id,
              metadata
            ) VALUES (
              ${prompt},
              ${enhancedPrompt},
              ${image.url},
              ${image.publicId},
              'imagen-3.0-generate-001',
              'vertex-ai',
              ${image.width},
              ${image.height},
              ${contentId || null},
              ${JSON.stringify({
                aspectRatio,
                numberOfImages,
                language,
                personGeneration,
                safetySetting,
                addWatermark,
                format: image.format,
                responsiveUrls: image.responsiveUrls,
                generatedAt: new Date().toISOString(),
                vertexImageId: vertexResult[0].id
              })}
            )
            ON CONFLICT (cloudinary_public_id) DO NOTHING
            RETURNING id, image_url, cloudinary_public_id
          `;

          records.push(vertexResult[0]);
        } catch (error) {
          console.error("Error saving image to database:", error);
          // Continue with other images even if one fails
        }
      }

      return records;
    });

    // Step 6: Update content if contentId provided
    if (contentId && savedRecords.length > 0) {
      await step.run("update-content-image", async () => {
        // Use the first generated image as the main content image
        const mainImage = savedRecords[0];

        await sql`
          UPDATE generated_content
          SET
            image_url = ${mainImage.image_url},
            image_prompt = ${enhancedPrompt},
            metadata = jsonb_set(
              COALESCE(metadata, '{}'),
              '{vertexAiImage}',
              ${JSON.stringify({
                generatedAt: new Date().toISOString(),
                imageId: mainImage.id,
                cloudinaryPublicId: mainImage.cloudinary_public_id,
                allImages: savedRecords.map(r => ({
                  id: r.id,
                  url: r.image_url,
                  publicId: r.cloudinary_public_id
                }))
              })}::jsonb
            ),
            updated_at = NOW()
          WHERE id = ${contentId}
        `;

        console.log(`Updated content ${contentId} with Vertex AI generated image`);
      });
    }

    // Step 7: Log the operation
    await step.run("log-operation", async () => {
      await sql`
        INSERT INTO event_logs (
          event_name,
          event_type,
          status,
          payload,
          metadata
        ) VALUES (
          'vertex-ai.image.generated',
          'image_generation',
          'completed',
          ${JSON.stringify({
            prompt: prompt.substring(0, 500),
            enhancedPrompt: enhancedPrompt.substring(0, 500),
            contentId,
            imagesGenerated: savedRecords.length
          })},
          ${JSON.stringify({
            model: 'imagen-3.0-generate-001',
            provider: 'vertex-ai',
            aspectRatio,
            numberOfImages,
            language,
            safetySetting,
            imageIds: savedRecords.map(r => r.id),
            cloudinaryPublicIds: savedRecords.map(r => r.cloudinary_public_id),
            timestamp: new Date().toISOString()
          })}
        )
      `;
    });

    return {
      success: true,
      message: `Successfully generated ${savedRecords.length} image(s) with Vertex AI`,
      images: savedRecords.map(record => ({
        id: record.id,
        url: record.image_url,
        cloudinaryPublicId: record.cloudinary_public_id
      })),
      prompt: enhancedPrompt,
      model: 'imagen-3.0-generate-001',
      provider: 'vertex-ai'
    };
  }
);

// Bulk generate images with Vertex AI
export const generateBulkImagesWithVertexAI = inngest.createFunction(
  {
    id: "generate-bulk-images-vertex-ai",
    name: "Generate Bulk Images with Vertex AI",
    retries: 1
  },
  {
    event: "image/vertex-ai.bulk-generate.requested"
  },
  async ({ event, step }) => {
    const { prompts, contentIds, options = {} } = event.data;

    if (!prompts || !Array.isArray(prompts) || prompts.length === 0) {
      throw new Error("No prompts provided for bulk generation");
    }

    // Step 1: Queue individual generation requests
    const queuedRequests = await step.run("queue-generation-requests", async () => {
      const requests = [];

      for (let i = 0; i < prompts.length; i++) {
        const prompt = prompts[i];
        const contentId = contentIds ? contentIds[i] : undefined;

        // Send individual generation event
        await inngest.send({
          name: "image/vertex-ai.generate.requested",
          data: {
            prompt,
            contentId,
            ...options // Spread common options
          }
        });

        requests.push({
          prompt: prompt.substring(0, 100),
          contentId
        });

        console.log(`Queued Vertex AI generation request ${i + 1}/${prompts.length}`);

        // Add a small delay between requests to avoid rate limiting
        if (i < prompts.length - 1) {
          await new Promise(resolve => setTimeout(resolve, 1000));
        }
      }

      return requests;
    });

    // Step 2: Log bulk operation
    await step.run("log-bulk-operation", async () => {
      await sql`
        INSERT INTO event_logs (
          event_name,
          event_type,
          status,
          payload,
          metadata
        ) VALUES (
          'vertex-ai.bulk.queued',
          'image_generation',
          'completed',
          ${JSON.stringify({
            totalRequests: queuedRequests.length,
            requests: queuedRequests
          })},
          ${JSON.stringify({
            options,
            timestamp: new Date().toISOString()
          })}
        )
      `;
    });

    return {
      success: true,
      message: `Queued ${queuedRequests.length} Vertex AI image generation requests`,
      queuedCount: queuedRequests.length,
      requests: queuedRequests
    };
  }
);

// Generate image for blog post with automatic prompt generation
export const generateBlogImageWithVertexAI = inngest.createFunction(
  {
    id: "generate-blog-image-vertex-ai",
    name: "Generate Blog Image with Vertex AI",
    retries: 2
  },
  {
    event: "blog/vertex-ai.image.generate.requested"
  },
  async ({ event, step }) => {
    const {
      blogId,
      prompt: providedPrompt,
      aspectRatio = "16:9", // Default to landscape for blog
      ...otherOptions
    } = event.data;

    // Step 1: Get blog content and prompt
    const blogData = await step.run("fetch-blog-and-prompt", async () => {
      const result = await sql`
        SELECT
          id,
          title,
          topic,
          keywords,
          content,
          image_prompt,
          image_url
        FROM generated_content
        WHERE id = ${blogId}
        LIMIT 1
      `;

      if (result.length === 0) {
        throw new Error(`Blog post not found with ID: ${blogId}`);
      }

      const blog = result[0];

      // Check if image already exists
      if (blog.image_url && !event.data.forceRegenerate) {
        console.log(`Blog ${blogId} already has an image: ${blog.image_url}`);
        return {
          ...blog,
          skipGeneration: true
        };
      }

      return blog;
    });

    // Skip if image already exists
    if (blogData.skipGeneration) {
      return {
        success: true,
        message: "Blog already has an image",
        existingImageUrl: blogData.image_url
      };
    }

    // Step 2: Determine or generate prompt
    const finalPrompt = await step.run("determine-prompt", async () => {
      // Priority: provided prompt > existing image_prompt > generate new
      if (providedPrompt) {
        console.log(`Using provided prompt for blog ${blogId}`);
        return providedPrompt;
      }

      if (blogData.image_prompt) {
        console.log(`Using existing image prompt for blog ${blogId}`);
        return blogData.image_prompt;
      }

      // Generate prompt based on blog content
      console.log(`Generating new prompt for blog ${blogId}`);

      // Create a context-aware prompt based on the blog topic
      const topicPrompts: Record<string, string> = {
        "Isı Pompası": "modern heat pump system installation in luxury Bodrum villa, professional HVAC equipment, energy efficient heating cooling technology",
        "Güneş Enerjisi": "solar panel installation on Mediterranean rooftop, photovoltaic system in Bodrum, sustainable energy solution",
        "Klima Sistemleri": "modern VRF air conditioning system, multi-split climate control installation, professional HVAC technology",
        "Su Arıtma": "advanced water treatment facility, reverse osmosis purification system, industrial water filtration technology",
        "Havuz Sistemleri": "luxury swimming pool with advanced filtration, modern pool equipment room, professional pool maintenance systems",
        "Mekanik Tesisat": "professional mechanical installation, industrial piping systems, HVAC mechanical room equipment"
      };

      let basePrompt = topicPrompts[blogData.topic] ||
        "professional engineering equipment installation, modern industrial technology, Bodrum Turkey";

      // Add title context if available
      if (blogData.title) {
        const titleKeywords = blogData.title
          .toLowerCase()
          .replace(/[^\w\s]/g, ' ')
          .split(' ')
          .filter((word: string) => word.length > 4)
          .slice(0, 3)
          .join(' ');

        if (titleKeywords) {
          basePrompt = `${titleKeywords}, ${basePrompt}`;
        }
      }

      // Add professional photography style
      basePrompt += ", professional architectural photography, bright daylight, clean modern design, high resolution, no people, no text, no logos";

      return basePrompt;
    });

    // Step 3: Save prompt to blog if it was generated
    if (!providedPrompt && !blogData.image_prompt) {
      await step.run("save-generated-prompt", async () => {
        await sql`
          UPDATE generated_content
          SET image_prompt = ${finalPrompt}
          WHERE id = ${blogId}
        `;
        console.log(`Saved generated prompt for blog ${blogId}`);
      });
    }

    // Step 4: Trigger Vertex AI image generation
    const generationResult = await step.run("trigger-vertex-ai-generation", async () => {
      // Send the generation event
      await inngest.send({
        name: "image/vertex-ai.generate.requested",
        data: {
          prompt: finalPrompt,
          contentId: blogId,
          aspectRatio,
          numberOfImages: 1,
          language: "en",
          safetySetting: "block_some",
          personGeneration: "dont_allow",
          addWatermark: false,
          ...otherOptions
        }
      });

      return {
        prompt: finalPrompt,
        blogId
      };
    });

    return {
      success: true,
      message: `Vertex AI image generation triggered for blog ${blogId}`,
      blogId,
      prompt: generationResult.prompt,
      aspectRatio
    };
  }
);

