import { NextResponse } from 'next/server';
import { sql } from '@/lib/db';
import { v2 as cloudinary } from 'cloudinary';

// Configure Cloudinary
cloudinary.config({
  cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
  api_key: process.env.CLOUDINARY_API_KEY,
  api_secret: process.env.CLOUDINARY_API_SECRET,
});

async function generateWithFalAI(prompt: string) {
  const apiKey = process.env.FAL_AI_KEY;
  if (!apiKey) {
    throw new Error("FAL_AI_KEY environment variable is not set");
  }

  try {
    const apiUrl = `https://fal.run/fal-ai/imagen4/preview/fast`;
    
    const response = await fetch(apiUrl, {
      method: "POST",
      headers: {
        "Authorization": `Key ${apiKey}`,
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        prompt,
        image_size: "landscape_16_9",
        num_inference_steps: 4,
        guidance_scale: 7.5,
        num_images: 1,
        enable_safety_checker: true,
        seed: Math.floor(Math.random() * 1000000)
      })
    });

    if (!response.ok) {
      const error = await response.text();
      throw new Error(`Fal.ai API error: ${response.status} - ${error}`);
    }

    const data = await response.json();
    return data;
  } catch (error) {
    console.error("Error generating image with Fal.ai:", error);
    throw error;
  }
}

async function uploadToCloudinary(imageUrl: string, prompt: string) {
  try {
    const result = await cloudinary.uploader.upload(imageUrl, {
      folder: 'fal-ai-generated',
      public_id: `fal-ai-${Date.now()}`,
      tags: ['ai-generated', 'fal-ai'],
      context: {
        prompt: prompt.slice(0, 200),
        generated_at: new Date().toISOString(),
        ai_model: 'fal-ai'
      },
      transformation: [
        { quality: 'auto:best' },
        { fetch_format: 'auto' }
      ]
    });

    return {
      url: result.secure_url,
      publicId: result.public_id
    };
  } catch (error) {
    console.error('Error uploading to Cloudinary:', error);
    throw error;
  }
}

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const { blogId, prompt } = body;

    if (!blogId || !prompt) {
      return NextResponse.json(
        { error: 'blogId and prompt are required' },
        { status: 400 }
      );
    }

    console.log(`🧪 Testing blog image generation for blog ${blogId}`);
    console.log(`📝 Prompt: ${prompt}`);

    // Step 1: Check blog exists
    console.log('🔍 Step 1: Checking blog exists...');
    const blog = await sql`
      SELECT id, title, topic, status
      FROM generated_content
      WHERE id = ${blogId}
    `;

    if (blog.length === 0) {
      return NextResponse.json(
        { error: 'Blog not found' },
        { status: 404 }
      );
    }

    console.log(`✅ Blog found: ${blog[0].title}`);

    // Step 2: Generate image with Fal.ai
    console.log('🎨 Step 2: Generating image with Fal.ai...');
    const falResponse = await generateWithFalAI(prompt);
    console.log(`✅ Fal.ai generated image:`, falResponse);

    // Step 3: Upload to Cloudinary
    console.log('☁️ Step 3: Uploading to Cloudinary...');
    const image = falResponse.images[0];
    if (!image) {
      throw new Error('No image generated by Fal.ai');
    }

    const cloudinaryResult = await uploadToCloudinary(image.url, `Blog: ${blog[0].title} - ${prompt}`);
    console.log(`✅ Cloudinary upload successful:`, cloudinaryResult);

    // Step 4: Update blog record
    console.log('💾 Step 4: Updating blog record...');
    await sql`
      UPDATE generated_content
      SET 
        image_url = ${cloudinaryResult.url},
        image_prompt = ${prompt},
        updated_at = ${new Date().toISOString()}
      WHERE id = ${blogId}
    `;

    // Step 5: Get updated blog record
    const updatedBlog = await sql`
      SELECT id, title, image_url, image_prompt, updated_at
      FROM generated_content
      WHERE id = ${blogId}
    `;

    console.log(`✅ Blog updated successfully:`, updatedBlog[0]);

    return NextResponse.json({
      success: true,
      blog: updatedBlog[0],
      falResponse,
      cloudinaryResult,
      message: `Successfully generated and assigned image to blog: ${blog[0].title}`
    });

  } catch (error) {
    console.error('❌ Test failed:', error);
    return NextResponse.json(
      { 
        success: false, 
        error: error instanceof Error ? error.message : 'Unknown error',
        details: error
      },
      { status: 500 }
    );
  }
}