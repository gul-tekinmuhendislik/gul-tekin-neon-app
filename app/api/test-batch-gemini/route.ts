import { NextResponse } from 'next/server';
import { inngest } from '@/lib/inngest/client';

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const {
      prompts = [
        "Modern mühendislik ofisi tasarımı",
        "Endüstriyel otomasyon sistemleri",
        "Yenilenebilir enerji çözümleri"
      ],
      style = "professional"
    } = body;

    // Toplu resim üretimi başlat
    const event = await inngest.send({
      name: "image.batch.generate.gemini",
      data: {
        prompts: prompts,
        style: style,
        brandId: "gul-tekin"
      }
    });

    return NextResponse.json({
      success: true,
      message: "Batch image generation started",
      eventId: event.ids,
      details: {
        totalPrompts: prompts.length,
        style: style,
        process: "Each prompt will be optimized by Gemini and generated by Fal.ai"
      }
    });
  } catch (error) {
    console.error("Error:", error);
    return NextResponse.json(
      { success: false, error: "Failed to trigger batch generation" },
      { status: 500 }
    );
  }
}

export async function GET() {
  return NextResponse.json({
    message: "Batch Image Generation with Gemini",
    usage: {
      method: "POST",
      body: {
        prompts: ["array of prompts"],
        style: "style preference"
      }
    },
    example: {
      prompts: [
        "Modern mühendislik ofisi",
        "Endüstriyel robot kolu",
        "Güneş paneli sistemi"
      ],
      style: "photorealistic"
    }
  });
}